import { expect, test } from '@playwright/test'
import { closeAudiences, createDeck, joinAudience, poll, presenterAction, quiz } from './helpers'

test.afterEach(closeAudiences)

for (const width of [390, 1280]) for (const mode of ['light', 'dark']) {
  test(`save state and modal keyboard ${width} ${mode}`, async ({ page, request }, info) => {
    const deck = await createDeck(request, `First-use ${width} ${mode}`, [poll('Original?', ['A', 'B'])])
    await page.setViewportSize({ width, height: 844 })
    await page.addInitScript(({ token, mode }) => {
      localStorage.setItem('livepoll.token', token)
      localStorage.setItem('livepoll.user', JSON.stringify({ id: 'e2e', username: 'e2e' }))
      localStorage.setItem('crowdflow.colorMode', mode)
    }, { token: deck.token, mode })
    await page.goto(`/edit/${deck.id}`)
    const dialogs: string[] = []
    page.on('dialog', async dialog => { dialogs.push(dialog.message()); await dialog.dismiss() })
    await expect(page.getByRole('status').filter({hasText:'No unsaved changes'})).toBeVisible()
    await page.getByLabel('Question', {exact:true}).fill('Saved question?')
    await expect(page.getByRole('status').filter({hasText:'Unsaved changes'})).toBeVisible()
    await page.getByRole('button', {name:'Save',exact:true}).click()
    await expect(page.getByRole('status').filter({hasText:/^Saved /})).toBeVisible()
    await page.screenshot({ path: info.outputPath(`editor-${width}-${mode}.png`) })
    await page.getByRole('link', {name:'Present',exact:true}).click()
    await expect(page).toHaveURL(`/present/${deck.code}`)
    expect(dialogs).toEqual([])
    await page.goto(`/edit/${deck.id}`)
    await page.getByLabel('Question', {exact:true}).fill('Not saved?')
    await page.getByRole('link', {name:'Present',exact:true}).click()
    expect(dialogs).toEqual(['You have unsaved changes. Leave without saving?'])
    await expect(page).toHaveURL(`/edit/${deck.id}`)
    // Undo back to the saved value clears the dirty state; redo restores it.
    await page.getByRole('button', {name:'Undo',exact:true}).click()
    await expect(page.getByLabel('Question', {exact:true})).toHaveValue('Saved question?')
    await expect(page.getByRole('status').filter({hasText:'No unsaved changes'})).toBeVisible()
    await page.goto('/dashboard')
    const opener = page.getByRole('button', {name:'+ New presentation'})
    await opener.click()
    const modal = page.getByRole('dialog', {name:'New presentation'})
    await expect(modal.getByLabel('Name', {exact:true})).toBeFocused()
    for (let i = 0; i < 12; i++) {
      await page.keyboard.press('Tab')
      expect(await modal.evaluate(el => el.contains(document.activeElement))).toBeTruthy()
    }
    for (let i = 0; i < 8; i++) {
      await page.keyboard.press('Shift+Tab')
      expect(await modal.evaluate(el => el.contains(document.activeElement))).toBeTruthy()
    }
    const selected = modal.getByRole('radio', {checked:true})
    await selected.focus()
    const previous = await selected.innerText()
    await page.keyboard.press('ArrowRight')
    await expect(modal.getByRole('radio', {checked:true})).toBeFocused()
    expect(await modal.getByRole('radio', {checked:true}).innerText()).not.toBe(previous)
    await page.screenshot({path:info.outputPath(`modal-${width}-${mode}.png`)})
    await page.keyboard.press('Escape')
    await expect(modal).toHaveCount(0)
    await expect(opener).toBeFocused()
    await expect(page.getByText('New code and blank answers. Keeps your slides and earlier results.').first()).toBeVisible()
    await expect(page.getByRole('link', {name:'Present existing run'}).first()).toBeVisible()
    await page.screenshot({path:info.outputPath(`dashboard-${width}-${mode}.png`)})
  })
}

test('quiz answer can change until reveal; ended poll replaces waiting UI', async ({browser,request}, info) => {
  const deck = await createDeck(request, 'Changeable quiz', [quiz('Closest planet?', ['Mercury', 'Venus'])])
  const audience = await joinAudience(browser,deck.code)
  await audience.getByRole('button', {name:/Generate nickname/}).click()
  await audience.getByRole('button', {name:'Save nickname'}).click()
  await audience.getByRole('button', {name:'Venus',exact:true}).click()
  await expect(audience.getByText(/Answer saved/)).toBeVisible()
  await audience.getByRole('button', {name:'Mercury',exact:true}).click()
  await expect(audience.getByRole('button', {name:'Mercury',exact:true})).toHaveClass(/chosen/)
  await presenterAction(request,deck,{type:'voting:set',open:false})
  await expect(audience.getByRole('button', {name:/Mercury/})).toBeDisabled()
  await audience.screenshot({path:info.outputPath('quiz-revealed.png')})
  const pollDeck = await createDeck(request, 'End poll', [poll('Next?', ['A', 'B'])])
  const phone = await joinAudience(browser,pollDeck.code)
  await phone.getByRole('button', {name:'A',exact:true}).click()
  await presenterAction(request,pollDeck,{type:'results:set',visible:false})
  await expect(phone.getByText('The presenter has hidden the results for now.')).toBeVisible()
  await presenterAction(request,pollDeck,{type:'presentation:end'})
  await expect(phone.getByRole('heading', {name:'Thanks for taking part!'})).toBeVisible()
  await expect(phone.getByText(/hidden.*for now|waiting for the presenter/i)).toHaveCount(0)
  await expect(phone.locator('.option-button')).toHaveCount(0)
  await expect(phone.getByRole('link', {name:'Join another presentation'})).toBeVisible()
  await phone.screenshot({path:info.outputPath('ended-phone.png')})
})

test('a fresh starter is unsaved until saved, and create keeps keyboard operation', async ({page,request}) => {
  const deck = await createDeck(request, 'Starter auth', [poll('Seed?', ['A', 'B'])])
  await page.addInitScript(token => {
    localStorage.setItem('livepoll.token',token)
    localStorage.setItem('livepoll.user',JSON.stringify({id:'e2e',username:'e2e'}))
  },deck.token)
  await page.goto('/dashboard')
  await page.getByRole('button',{name:'+ New presentation'}).click()
  const modal=page.getByRole('dialog',{name:'New presentation'})
  await modal.getByLabel('Name',{exact:true}).fill('Fresh quiz')
  await modal.getByRole('button',{name:'Create',exact:true}).click()
  await expect(page).toHaveURL(/\/edit\//)
  await expect(page.getByRole('status').filter({hasText:'Unsaved changes'})).toBeVisible()
  await expect(page.getByTestId('sorter-item')).toHaveCount(1)
})
