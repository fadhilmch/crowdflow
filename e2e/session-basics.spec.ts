import { expect, test } from '@playwright/test'
import { closeAudiences, createDeck, joinAudience, poll, presenterAction } from './helpers'

test.afterEach(closeAudiences)

test('phone poll results update, hide/reveal and survive reload; End reaches phones', async ({ browser, request }) => {
  const deck = await createDeck(request, 'Friday decisions', [poll('Where should we meet?', ['At the office', 'At the cafe'])])
  const phone = await joinAudience(browser, deck.code)
  await phone.locator('.option-button').first().click()
  const results = phone.getByRole('region', { name: 'Room results' })
  await expect(results).toContainText('1 vote')
  await expect(results).toContainText('100%')
  await expect(results.locator('.result-fill').first()).toHaveCSS('width', '300px')
  await phone.screenshot({ path: '/tmp/tier1-poll-mobile.png', fullPage: true })
  await presenterAction(request, deck, { type: 'results:set', visible: false })
  await expect(results).toHaveCount(0)
  await expect(phone.getByText('The presenter has hidden the results for now.')).toBeVisible()
  await phone.reload()
  await expect(phone.getByRole('region', { name: 'Room results' })).toHaveCount(0)
  await presenterAction(request, deck, { type: 'results:set', visible: true })
  await expect(results).toContainText('100%')
  const stage = await browser.newPage({ viewport: { width: 1280, height: 850 } })
  await stage.addInitScript((token) => { localStorage.setItem('livepoll.token', token); localStorage.setItem('livepoll.user', JSON.stringify({ id: 'e2e', username: 'e2e' })) }, deck.token)
  await stage.goto(`/present/${deck.code}`)
  await stage.getByRole('button', { name: 'End', exact: true }).click()
  await stage.waitForURL('**/dashboard')
  await expect(phone.getByRole('heading', { name: 'Thanks for taking part!' })).toBeVisible()
  await expect(phone.locator('.option-button')).toHaveCount(0)
  await expect(phone.getByText(/waiting for the presenter/i)).toHaveCount(0)
  await phone.screenshot({ path: '/tmp/tier1-ended-mobile.png', fullPage: true })
  await phone.reload()
  await expect(phone.getByRole('heading', { name: 'Thanks for taking part!' })).toBeVisible()
  await stage.goto(`/present/${deck.code}`)
  await expect(stage.getByText('This presentation has ended', { exact: true })).toBeVisible()
  await stage.screenshot({ path: '/tmp/tier1-ended-desktop.png', fullPage: true })
  await stage.getByRole('button', { name: 'Present again' }).click()
  await expect(phone.locator('.option-button').first()).toBeEnabled()
  await stage.close()
})

test('ranking results show points on phones; empty decks offer an editor not a dead stage', async ({ browser, request }) => {
  const ranking = { questionType: 'ranking', question: 'Choose our priorities', options: [{ id: 'a', text: 'Speed' }, { id: 'b', text: 'Clarity' }] }
  const deck = await createDeck(request, 'Priorities', [ranking])
  const phone = await joinAudience(browser, deck.code)
  await phone.locator('.option-button').nth(1).click()
  await phone.locator('.option-button').nth(0).click()
  await phone.getByRole('button', { name: 'Send ranking' }).click()
  await expect(phone.getByRole('region', { name: 'Room results' })).toContainText('2 pts')
  await expect(phone.getByRole('region', { name: 'Room results' }).locator('.result-fill').first()).toHaveCSS('width', '300px')
  await phone.screenshot({ path: '/tmp/tier1-ranking-mobile.png', fullPage: true })
  const empty = await createDeck(request, 'Empty deck', [])
  const stage = await browser.newPage({ viewport: { width: 1280, height: 850 } })
  await stage.addInitScript((token) => { localStorage.setItem('livepoll.token', token); localStorage.setItem('livepoll.user', JSON.stringify({ id: 'e2e', username: 'e2e' })) }, empty.token)
  await stage.goto(`/present/${empty.code}`)
  await expect(stage.getByRole('heading', { name: 'Add a slide before presenting' })).toBeVisible()
  await stage.screenshot({ path: '/tmp/tier1-empty-desktop.png', fullPage: true })
  await stage.setViewportSize({ width: 390, height: 800 })
  await stage.screenshot({ path: '/tmp/tier1-empty-mobile.png', fullPage: true })
  await stage.getByRole('link', { name: 'Open editor' }).click()
  await stage.waitForURL(`**/edit/${empty.id}`)
  await expect(stage.getByText('Add and save a slide to present.')).toBeVisible()
  await expect(stage.getByRole('link', { name: 'Present', exact: true })).toHaveCount(0)
  await stage.close()
})


test('ending a separate session pushes a terminal state before its code is released', async ({ browser, request }) => {
  test.skip(process.env.E2E_SESSIONS !== 'true', 'needs session flag')
  const deck = await createDeck(request, 'Separate run', [poll('Pick a plan', ['Plan A', 'Plan B'])])
  const created = await request.post(`/api/presentations/${deck.id}/sessions`, { headers: { authorization: `Bearer ${deck.token}` } })
  expect(created.ok()).toBeTruthy()
  const run = (await created.json()).data
  const phone = await joinAudience(browser, run.code)
  await phone.locator('.option-button').first().click()
  const end = await request.post(`/api/sessions/${run.id}/end`, { headers: { authorization: `Bearer ${deck.token}` } })
  expect(end.ok()).toBeTruthy()
  await expect(phone.getByRole('heading', { name: 'Thanks for taking part!' })).toBeVisible()
  await expect(phone.locator('.option-button')).toHaveCount(0)
  expect((await request.get(`/api/live/${run.code}/state`)).status()).toBe(410)
})

test('reopening or joining an ended session says it ended, not "no presentation"', async ({ browser, request }) => {
  test.skip(process.env.E2E_SESSIONS !== 'true', 'needs session flag')
  const deck = await createDeck(request, 'Ended reload', [poll('Pick', ['A', 'B'])])
  const run = (await (await request.post(`/api/presentations/${deck.id}/sessions`, { headers: { authorization: `Bearer ${deck.token}` } })).json()).data
  await request.post(`/api/sessions/${run.id}/end`, { headers: { authorization: `Bearer ${deck.token}` } })
  const ctx = await browser.newContext({ viewport: { width: 390, height: 800 } })
  const phone = await ctx.newPage()
  await phone.goto(`/p/${run.code}`)
  await expect(phone.getByRole('heading', { name: 'Thanks for taking part!' })).toBeVisible()
  await expect(phone.getByText('The presenter has ended this presentation.')).toBeVisible()
  await expect(phone.getByText('ended or was deleted')).toHaveCount(0)
  await expect(phone.getByText('Connecting…')).toHaveCount(0)
  await phone.screenshot({ path: '/tmp/ended-after-reload-390.png' })
  await phone.goto('/join')
  await phone.getByRole('textbox').first().fill(run.code)
  await phone.keyboard.press('Enter')
  await expect(phone.getByRole('alert')).toContainText('This session has ended')
  await phone.screenshot({ path: '/tmp/ended-after-join-390.png' })
  await ctx.close()
})

